/**
 * Функция для получения сообщения по ключу
 * @param {string} key - Ключ сообщения
 * @returns {string|null} - HTML строка с сообщением или null, если ключ не найден
 */
export const getValidationMessage = (key) => {
  const messageObj = validationMessages.find(msg => msg.key === key);
  if (!messageObj) return null;
  return `<span class="p1">${messageObj.title}</span> <br>${messageObj.message}`;
};













